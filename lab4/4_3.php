<?php
$vehicle = "car";

switch ($vehicle) {
    case "bus":
        print "Beep beep";
        break;
    case "train":
        print "Runs on tracks";
        break;
    case "car":
        print "Has at least three wheels";
        break;
    case "helicopter":
        print "Can fly";
        break;
    case "bicycle":
        print "You never forget once you've learned";
        break;
    default:
        print "You've chosen the road less traveled";
}
